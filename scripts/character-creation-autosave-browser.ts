import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type pg from "pg";
import type { Page } from "playwright-core";

export async function rehearseCharacterCreationAutosave(pool: pg.Pool, login: (id: string) => Promise<Page>, baseUrl: string, characters: number[]) {
  assert.equal((await pool.query("select current_database() name")).rows[0].name, "serrian_character_sheet_dev");
  const out = path.resolve("artifacts/character-creation-autosave"); await mkdir(out, { recursive: true });
  const characterId = characters[1], campaignId = (await pool.query("select campaign_id from campaign_character where id=$1", [characterId])).rows[0].campaign_id;
  await pool.query("update campaign set skill_points=100 where id=$1", [campaignId]);
  const race = (await pool.query("insert into races(name,size,base_magic) values('Draft Riverfolk','Medium',4) returning id")).rows[0].id;
  await pool.query("insert into campaign_race(campaign_id,race_id,sort_order) select $1,$2,coalesce(max(sort_order),-1)+1 from campaign_race where campaign_id=$1", [campaignId, race]);
  await pool.query("insert into campaign_allowed_race(campaign_id,race_id,sort_order) select $1,$2,coalesce(max(sort_order),-1)+1 from campaign_allowed_race where campaign_id=$1", [campaignId, race]);
  for (const name of ["Trailcraft", "Trail Signs"]) await pool.query("insert into skill(name,classification,tier,primary_attribute,created_by_user_id) values($1,'standard',1,'WIS','sheet-owner')", [name]);
  const tables = (await pool.query("select table_name from information_schema.tables where table_schema='public' and (table_name='campaign_character' or starts_with(table_name,'campaign_character_')) order by table_name")).rows;
  const fingerprint = async () => Promise.all(tables.map(async ({ table_name: table }) => {
    assert.match(table, /^campaign_character(?:_[a-z_]+)?$/);
    return (await pool.query(`select coalesce(jsonb_agg(to_jsonb(r) order by to_jsonb(r)::text),'[]'::jsonb) value from "${table}" r`)).rows[0].value;
  }));
  const page = await login("sheet-player"); page.on("dialog", dialog => void dialog.accept());
  const url = `${baseUrl}/realms/characters/${characterId}`;
  const ready = async (target = page) => {
    await target.waitForFunction(() => { const input = document.querySelector<HTMLInputElement>('.character-editor input'); return input && !input.disabled; });
  };
  const entries = async (target = page) => target.evaluate(() => Object.entries(localStorage).filter(([key]) => key.startsWith("serrian-character-creation:v1:")).map(([key, raw]) => ({ key, raw, value: JSON.parse(raw) })));
  await page.goto(`${baseUrl}/realms`); await page.goto(url); await ready();
  const before = await fingerprint();
  await page.getByLabel(/Character Name/).fill("Kept after Back");
  await page.getByLabel(/^Race/).selectOption(String(race));
  await page.waitForFunction(() => !document.querySelector<HTMLSelectElement>('.character-editor select')?.disabled);
  await page.getByRole("tab", { name: "Attributes", exact: true }).click();
  await page.getByLabel("Strength Score", { exact: true }).fill("29");
  await page.getByLabel("Dexterity Score", { exact: true }).fill("31");
  await page.getByRole("tab", { name: "Story & Personality", exact: true }).click();
  await page.getByLabel(/Backstory/).fill("A draft story that must survive an accidental Back click.");
  await page.getByLabel(/Secrets/).fill("My private unfinished secret.");
  await page.getByRole("tab", { name: "Skills & Abilities", exact: true }).click();
  await page.getByRole("tab", { name: /^Wisdom/ }).click();
  await page.getByLabel("Trailcraft Points Invested", { exact: true }).fill("5");
  await page.getByRole("tab", { name: "Equipment", exact: true }).click();
  await page.getByLabel("Restorative Wand Quantity", { exact: true }).fill("1");
  await page.getByText("Draft autosaved on this device. Save Character updates the saved record.", { exact: true }).waitFor();
  const original = (await entries())[0].value;
  assert.equal(original.draft.profile.raceId, race); assert.equal(original.draft.attributes.DEX, 31);
  assert.equal(original.draft.itemInstances.length, 1); assert.ok(original.draft.itemInstances[0].draftId < 0);
  assert.deepEqual(await fingerprint(), before, "Device autosave must never update the saved Character or runtime");
  await page.goBack(); await page.waitForURL(`${baseUrl}/realms`);
  await page.goForward(); await page.waitForURL(url);
  await page.waitForFunction(() => { const input = document.querySelector<HTMLInputElement>('input[aria-label="Restorative Wand Quantity"]'); return input?.value === "1" && !input.disabled; });
  await page.reload({ waitUntil: "domcontentloaded" });
  await page.getByText(/^Recovered your autosaved creation draft/).waitFor();
  assert.equal(await page.getByRole("tab", { name: "Equipment", exact: true }).getAttribute("aria-selected"), "true");
  assert.equal(await page.getByLabel("Restorative Wand Quantity", { exact: true }).inputValue(), "1");
  await page.getByRole("tab", { name: "Identity", exact: true }).click(); await ready();
  assert.equal(await page.getByLabel(/Character Name/).inputValue(), "Kept after Back");
  assert.equal(await page.getByLabel(/^Race/).inputValue(), String(race));
  await page.getByRole("tab", { name: "Attributes", exact: true }).click();
  assert.equal(await page.getByLabel("Strength Score", { exact: true }).inputValue(), "29");
  assert.equal(await page.getByLabel("Dexterity Score", { exact: true }).inputValue(), "31");
  await page.getByRole("tab", { name: "Story & Personality", exact: true }).click();
  assert.match(await page.getByLabel(/Backstory/).inputValue(), /must survive/);
  assert.equal(await page.getByLabel(/Secrets/).inputValue(), "My private unfinished secret.");
  await page.getByRole("tab", { name: "Skills & Abilities", exact: true }).click();
  await page.getByRole("tab", { name: /^Wisdom/ }).click();
  assert.equal(await page.getByLabel("Trailcraft Points Invested", { exact: true }).inputValue(), "5");
  await page.getByLabel("Trail Signs Points Invested", { exact: true }).fill("6");
  await page.getByRole("tab", { name: "Equipment", exact: true }).click();
  await page.getByLabel("Restorative Wand Quantity", { exact: true }).fill("2");
  const recovered = (await entries())[0].value;
  assert.equal(new Set(recovered.draft.skillAllocations.map((row: { draftId: number }) => row.draftId)).size, recovered.draft.skillAllocations.length);
  assert.equal(new Set(recovered.draft.itemInstances.map((row: { draftId: number }) => row.draftId)).size, 2);
  assert.deepEqual(await fingerprint(), before, "Restoring and continuing a draft remains read-only until Save Character");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(out, "recovered-phone.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });

  const other = await page.context().newPage(); other.on("dialog", dialog => void dialog.accept());
  await other.goto(url); await other.getByText(/^Recovered your autosaved creation draft/).waitFor();
  await other.getByRole("tab", { name: "Identity", exact: true }).click();
  await other.getByLabel(/Character Name/).fill("Second window draft");
  await page.getByRole("tab", { name: "Identity", exact: true }).click();
  const independent = await entries();
  assert.equal(independent.length, 2);
  assert.deepEqual(new Set(independent.map(entry => entry.value.draft.name)), new Set(["Kept after Back", "Second window draft"]));
  await other.close();

  const owner = await login("sheet-owner");
  await owner.evaluate(rows => rows.forEach(({ key, raw }) => localStorage.setItem(key, raw)), independent);
  await owner.goto(`${baseUrl}/heavens/characters/${characterId}`); await ready(owner);
  assert.equal(await owner.getByLabel(/Character Name/).inputValue(), "Rowan Draft", "Another account must never receive this Player's device draft");
  assert.equal(await owner.locator('.character-draft-recovery').count(), 0);
  await owner.close();
  assert.deepEqual(await fingerprint(), before, "Independent windows and account-isolated recovery never write the database");

  await page.reload();
  await page.getByRole("region", { name: "Recover Character draft", exact: true }).waitFor();
  await page.getByRole("button", { name: /^Recover Kept after Back/ }).click();
  await ready();
  assert.equal(await page.getByLabel(/Character Name/).inputValue(), "Kept after Back");
  await page.getByRole("button", { name: "Save Character", exact: true }).click();
  await page.getByText("Character draft saved.", { exact: true }).waitFor();
  const retained = await entries();
  assert.equal(retained.length, 1, "Saving retires only this editor's acknowledged packet");
  assert.equal(retained[0].value.draft.name, "Second window draft");
  const saved = (await pool.query("select c.name,p.race_id,p.backstory,p.creation_completed_at from campaign_character c join campaign_character_profile p on p.character_id=c.id where c.id=$1", [characterId])).rows[0];
  assert.equal(saved.name, "Kept after Back"); assert.equal(saved.race_id, race); assert.match(saved.backstory, /must survive/); assert.equal(saved.creation_completed_at, null);
  await page.reload();
  await page.getByRole("region", { name: "Recover Character draft", exact: true }).waitFor();
  await page.getByRole("button", { name: "Discard listed drafts and use saved Character", exact: true }).click(); await ready();
  assert.equal((await entries()).length, 0);
  assert.equal(await page.getByLabel(/Character Name/).inputValue(), "Kept after Back");
  assert.equal(await page.locator('.character-draft-recovery').count(), 0);
  await page.screenshot({ path: path.join(out, "saved-desktop.png"), fullPage: true });

  const blocked = await page.context().newPage();
  await blocked.addInitScript(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function (key, value) { if (key.startsWith("serrian-character-creation:v1:")) throw new DOMException("Storage unavailable", "QuotaExceededError"); original.call(this, key, value); };
  });
  await blocked.goto(url); await ready(blocked);
  await blocked.getByLabel(/Character Name/).fill("Explicit save still works");
  await blocked.getByRole("alert").filter({ hasText: "Device backup is unavailable" }).waitFor();
  assert.equal((await pool.query("select name from campaign_character where id=$1", [characterId])).rows[0].name, "Kept after Back");
  await blocked.getByRole("button", { name: "Save Character", exact: true }).click();
  await blocked.getByText("Character draft saved.", { exact: true }).waitFor();
  assert.equal((await pool.query("select name from campaign_character where id=$1", [characterId])).rows[0].name, "Explicit save still works");
  await blocked.close();

  const locked = await page.context().newPage();
  await locked.goto(`${baseUrl}/realms/characters/${characters[0]}`);
  assert.equal(await locked.getByLabel(/Character Name/).isDisabled(), true);
  assert.equal(await locked.locator('.character-creation-autosave, .character-draft-recovery').count(), 0);
  await locked.close();
  await writeFile(path.join(out, "browser-receipt.json"), JSON.stringify({ passed: true, checks: ["local-only writes", "Back/Forward/reload", "Race and full profile", "attributes", "skills", "exact item copies", "temporary identity continuation", "active tab", "phone", "independent windows", "account isolation", "changed saved-record choice", "explicit save and conditional retirement", "storage unavailable / manual save", "completed record lock", "creation stays open"] }, null, 2));
  console.log("PASS: device-only creation autosave, actual Back/Forward/reload recovery, complete draft fields and explicit save.");
}
